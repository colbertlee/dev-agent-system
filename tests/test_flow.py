def test_extract_code_blocks():
    from dev_agent_system.agents import BaseAgent
    text = "# file: foo.py\n```python\nprint(1)\n```"
    blocks = BaseAgent._extract_code_blocks(text)
    assert len(blocks) == 1
    assert blocks[0]["path"] == "foo.py"
