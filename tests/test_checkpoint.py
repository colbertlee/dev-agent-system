def test_sqlite_checkpoint_put_and_get(tmp_path):
    db = tmp_path / "ckpt.sqlite"
    saver = SQLiteCheckpointSaver(db_path=str(db))

    config = {"configurable": {"thread_id": "req-1", "checkpoint_ns": ""}}
    checkpoint = empty_checkpoint()
    metadata = {"source": "input", "step": -1, "writes": {}, "parents": {}}

    saver.put(config, checkpoint, metadata, {})
    result = saver.get_tuple({"configurable": {"thread_id": "req-1"}})

    assert result is not None
    assert result.checkpoint["id"] == checkpoint["id"]
    assert result.metadata["source"] == "input"
    assert result.checkpoint.get("pending_sends") == []


def test_sqlite_checkpoint_put_writes_and_list(tmp_path):
    db = tmp_path / "ckpt.sqlite"
    saver = SQLiteCheckpointSaver(db_path=str(db))

    config = {"configurable": {"thread_id": "req-2", "checkpoint_ns": ""}}
    checkpoint = empty_checkpoint()
    metadata = {"source": "loop", "step": 0, "writes": {}, "parents": {}}

    new_config = saver.put(config, checkpoint, metadata, {})
    saver.put_writes(new_config, [("channel1", "value1"), ("channel2", "value2")], "task-1")

    result = saver.get_tuple({"configurable": {"thread_id": "req-2"}})
    assert result is not None
    assert len(result.pending_writes) == 2
    channels = {w[1] for w in result.pending_writes}
    assert channels == {"channel1", "channel2"}

    checkpoints = list(saver.list({"configurable": {"thread_id": "req-2"}}))
    assert len(checkpoints) == 1


