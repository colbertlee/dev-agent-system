def test_orchestrator_persists_checkpoints(monkeypatch, tmp_path):
    """Orchestrator 执行后应产生 checkpoint，并能恢复至最终状态。"""
    monkeypatch.setattr(LLMClient, "chat", _mock_chat)
    monkeypatch.setenv("CHECKPOINT_DB", str(tmp_path / "ckpt.sqlite"))
    monkeypatch.setenv("CHECKPOINT_ENABLED", "true")

    async def _run():
        orch = Orchestrator(max_iterations=1)
        result = await orch.run("开发一个加法模块", request_id="ckpt-req-3")
        checkpoints = orch.list_checkpoints("ckpt-req-3")
        return result, checkpoints

    result, checkpoints = asyncio.run(_run())

    assert result["request_id"] == "ckpt-req-3"
    assert result["status"] == "completed"
    assert checkpoints
    assert Path(result["artifacts"]["workspace"]).exists()


def test_orchestrator_resume_from_checkpoint(monkeypatch, tmp_path):
    """先跑一次任务，再 resume；resume 应返回已完成的最终状态。"""
    monkeypatch.setattr(LLMClient, "chat", _mock_chat)
    monkeypatch.setenv("CHECKPOINT_DB", str(tmp_path / "ckpt.sqlite"))
    monkeypatch.setenv("CHECKPOINT_ENABLED", "true")

    async def _run_and_resume():
        orch = Orchestrator(max_iterations=1)
        first = await orch.run("开发一个加法模块", request_id="ckpt-req-4")
        resumed = await orch.resume("ckpt-req-4")
        return first, resumed

    first, resumed = asyncio.run(_run_and_resume())

    assert first["request_id"] == "ckpt-req-4"
    assert resumed["request_id"] == "ckpt-req-4"
    assert resumed["status"] == "completed"
